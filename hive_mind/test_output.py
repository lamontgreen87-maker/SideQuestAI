import asyncio
from overmind import Overmind

async def main():
    print("="*60)
    print("🚀 INITIALIZING IMPOSSIBLE ENGINE: STORY MODE")
    print("="*60)
    
    # 1. Define the High-Level Goal
    goal = """
    Create a 3-character plot outline for a Noir Detective story 
    titled 'The Shadow of the Hive'. 
    Theme: An AI detective solving its own murder across a sprawling megalopolis.
    """
    
    # 2. Start the Overmind
    # Redundancy factor of 2 for this demo (2 drones per task)
    hub = Overmind(redundancy_factor=2)
    
    print(f"\n[Overmind] Target Goal Locked: {goal.strip()}")
    print("[Overmind] Status: SHATTERING GOAL INTO ATOMIC PROTOCOLS...\n")
    
    # 3. Execute the Swarm
    # Depth 0: High-level shattering
    results = await hub.run_swarm(goal)
    
    print("\n" + "="*60)
    print("✅ HIVE SYNTHESIS COMPLETE")
    print("="*60)
    
    print("\n[Final God-Mode Output]:")
    print("-" * 30)
    for res in results:
        print(f"\n🔹 {res['outcome']}")
    print("-" * 30)
    
    print("\n[Engine Note]: This output was generated by a recursive swarm.")
    print("Every point above was 'rebutted' and verified by multiple workers.")

if __name__ == "__main__":
    asyncio.run(main())
